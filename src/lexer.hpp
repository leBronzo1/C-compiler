#pragma once

#include <cstdint>
#include <string>
#include <sstream>
#include <fstream>
#include <vector>

namespace lxr {
  // Enum representing different types of tokens in the source code
  enum class TokenTypes: std::uint8_t  {
    Int,
    Return,
    Lparen,
    Rparen,
    Lbrack,
    Rbrack,
    Plus,
    Minus,
    Number,
    Identifier,
    EndOfFile
  };

  // Token structure representing a single token in the source code
  struct Token {
    TokenTypes type; // The type of the token (e.g., Int, Return, Plus, etc.)
    std::string token; // The actual token string from the source code
  };

  // Lexer class for tokenizing source code
  class Lexer {
    private:
      std::stringstream source; // Stream containing the source code to be tokenized
      std::fstream file; // File stream for reading the source code from a file
      std::vector<Token> tokens; // Vector storing the tokens generated by the lexer
    public:
      explicit Lexer(const std::string& filename); // Constructor for the Lexer class, takes the filename of the source code to be tokenized
      std::vector<Token> tokenize(); // Method to tokenize the source code and return the vector of tokens
};
} // namespace lxr
